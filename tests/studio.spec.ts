test('author workflow: edit, save, reopen, checkpoint, publish, and restore', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/editor');
  await expect(page.getByRole('button', { name: /Open sample book/ })).toBeVisible();
  await page.screenshot({ path: 'artifacts/studio-library.png', fullPage: true });
  await page.getByRole('button', { name: /Open sample book/ }).click();
  await expect(page.getByLabel('Chapter content')).toContainText('The first thing I noticed');
  await page.getByLabel('Book title', { exact: true }).fill('A Book Worth Keeping');
  await page.getByLabel('Author name').fill('Test Author');
  await page.getByLabel('Chapter content').click();
  await page.keyboard.press('Control+End');
  await page.keyboard.type(' A sentence that must survive reopening.');
  await expect(page.getByText('Saved on this device', { exact: true })).toBeVisible();
  await page.screenshot({ path: 'artifacts/studio-workspace.png', fullPage: true });
  await page.getByLabel('Version history').click();
  await page.getByRole('button', { name: 'Save checkpoint' }).click();
  await expect(page.locator('.studio-notice')).toContainText('Checkpoint saved');
  await page.getByLabel('Back to library').click();
  await page.reload();
  await page.getByRole('button', { name: /A Book Worth Keeping/ }).click();
  await expect(page.getByLabel('Chapter content')).toContainText('A sentence that must survive reopening.');
  await page.getByRole('button', { name: 'Design', exact: true }).click();
  await expect(page.getByText(/measured pages/)).toBeVisible({ timeout: 60000 });
  await expect(page.locator('iframe[title="Book spread"]')).toBeVisible();
  await page.getByRole('tab', { name: 'Print' }).click();
  const frame = page.frameLocator('iframe[title="Measured book preview"]');
  await expect(frame.locator('.pagedjs_page')).not.toHaveCount(0);
  const previewPages = await frame.locator('.pagedjs_page').count();
  expect(await frame.locator('.pagedjs_page').first().evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgb(255, 255, 255)');
  await expect.poll(async () => frame.locator('.pagedjs_pages #section-1').evaluate(el => {
    const top = el.closest('.pagedjs_page')!.getBoundingClientRect().top;
    return top >= 0 && top < 100;
  })).toBe(true);
  await page.screenshot({ path: 'artifacts/studio-design.png', fullPage: true });
  await page.getByRole('button', { name: 'Export book', exact: true }).click();
  const epubDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: /Reading edition/ }).click();
  const epub = await epubDownload; await epub.saveAs('artifacts/test-book.epub');
  const fs = await import('node:fs/promises');
  const zip = await JSZip.loadAsync(await fs.readFile('artifacts/test-book.epub'));
  expect(await zip.file('EPUB/package.opf')!.async('string')).toContain('Test Author');
  expect(await zip.file('EPUB/section-1.xhtml')!.async('string')).toContain('A sentence that must survive reopening.');
  const backupDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download editable project' }).click();
  const backup = await backupDownload; await backup.saveAs('artifacts/test-book.booksane');
  const pdfDownload = page.waitForEvent('download', { timeout: 90000 });
  await page.getByRole('button', { name: /^Print interior · PDF Measured/ }).click();
  const pdf = await pdfDownload; await pdf.saveAs('artifacts/test-book.pdf');
  const document = await PDFDocument.load(await fs.readFile('artifacts/test-book.pdf'));
  expect(document.getPageCount()).toBeGreaterThan(3);
  expect(document.getPageCount()).toBe(previewPages);
  expect(document.getPage(0).getWidth()).toBeCloseTo(432, 0);
  expect(document.getPage(0).getHeight()).toBeCloseTo(648, 0);
  const pdfx = page.getByRole('button', { name: /Print interior · PDF\/X-1a/ });
  if (await pdfx.count()) {
    const xDownload = page.waitForEvent('download', { timeout: 120000 });
    await pdfx.click();
    const x = await xDownload; await x.saveAs('artifacts/test-book-pdfx.pdf');
    const bytes = await fs.readFile('artifacts/test-book-pdfx.pdf');
    expect(bytes.subarray(0, 8).toString()).toBe('%PDF-1.3');
    expect(bytes.toString('latin1')).toContain('GTS_PDFX');
    expect((await PDFDocument.load(bytes)).getPageCount()).toBe(previewPages);
  }
  await page.getByLabel('Close export').click();
  await page.getByLabel('Back to library').click();
  await page.locator('input[type=file]').first().setInputFiles('artifacts/test-book.booksane');
  await expect(page.getByLabel('Book title', { exact: true })).toHaveValue('A Book Worth Keeping');
  await expect(page.getByLabel('Chapter content')).toContainText('A sentence that must survive reopening.');
  expect(errors).toEqual([]);
});

